<!-- Script 1: Brid's player initialization and ad error handling -->
<script>
  // Primary Brid player init
  $bos("Brid_4745248596", { id: "37120", width: 640, height: 360 });

  // Error handling -> Fallback + Vidverto
  $bos("Brid_4745248596").on("adError", function() {
    console.log('Primary ad error, triggering fallback and passback.');

    // Fallback Brid player
    $bp("Brid_1528928361", { id: "46683", width: 640, height: 360, playlist: "25543" });
    $bp("Brid_1528928361").on("adError", function() {
      console.log('Fallback also failed. Destroying player.');
      $bp().destroy();
    });

    // Vidverto Passback
    var vvScript = document.createElement("script");
    vvScript.src = "https://ad.vidverto.io/vidverto/js/aries/v1/invocation.js";
    vvScript.async = true;
    document.head.appendChild(vvScript);

    vvScript.onload = function() {
      var container = document.getElementById("passback-div");
      window.top.aries = window.top.aries || {};
      window.top.aries.v1 = window.top.aries.v1 || { commands: [] };
      window.top.aries.v1.commands.push(function() {
        window.top.aries.v1.mount("7079", container, { width: 720, height: 405 });
      });
    };
  });
</script>

</body>
</html>
